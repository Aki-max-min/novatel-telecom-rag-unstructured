"""
Question set for the final performance measurement  ->  eval/perf_report/questions.jsonl  (+ review_gold.csv, counts)

    python eval/perf_report/build_questions.py

Sources (all read-only; nothing here is generated by a model):
  * the 22 original E14a questions                              is_core=true   gold_source "E14a"
        data/experiments/benchmark_base_vs_rag/queryset.json
  * 7 held-out database questions                               gold_source "Person B reference"
        structured/benchmark.json items S02 S05 S08 S10 S11 S13 S14 (the ones E14a did not use); ground truth is read from SQLite
  * 13 multi-hop questions read with `git show wip/e15-partial-unvalidated:eval/e15/queryset.json` (no checkout)
        MH01-05 (document <-> document)   written by Claude Code, UNREVIEWED
        MH12-13 (SQL <-> SQL)             written by Claude Code, UNREVIEWED  (values computed from SQLite)
        MH_RB_B01-06 (SQL + document)     facts and document ids from Person B's frozen route benchmark; the "For customer <id>:"
                                          prefix and the fact split were added by Claude Code

Categories: db | syn | trai | cross | multi
    db     E14a structured (8) + held-out database (7)
    syn    E14a synthetic-document questions (8)
    trai   E14a TRAI-document questions (6)
    cross  question that needs a database fact AND document policy (the 6 RB items)
    multi  multi-hop inside one source family: document<->document (5) and SQL<->SQL (2)

Gold facts. A fact is {"text", "kind": "sql"|"doc", "anchors": [...]}. Anchors are strings that must appear in a correct answer
(numbers are matched numerically). A fact without anchors is judged per fact by the local model at scoring time. The document half
of the 6 cross questions has no atomic facts in Person B's reference (only document ids and a vague policy note), so it is recorded as ONE
fact of kind "doc_policy", scored by the E14a correctness judge against the text of the gold documents -- no fact text is invented.

Re-verification (every gold item is checked against the actual data; failures are dropped and listed in questions_dropped.json):
  * every gold document id must exist in the CLEAN index (data/experiments/combined_retrieval_clean/vectorstore)
  * every SQL fact is re-queried in SQLite (table, primary key, field, value) and must match
  * every document anchor must occur in the text of its cited document
  * every database question's ground truth must be computable from SQLite (non-empty, except the S15 negative control)
"""

from __future__ import annotations

import csv
import json
import sqlite3
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "structured"))

from integration.eval import base_vs_rag as e14  # noqa: E402

OUT = ROOT / "eval" / "perf_report"
E14A = ROOT / "data" / "experiments" / "benchmark_base_vs_rag" / "queryset.json"
STRUCT_BENCH = ROOT / "structured" / "benchmark.json"
INDEX_META = ROOT / "data" / "experiments" / "combined_retrieval_clean" / "vectorstore" / "chunk_metadata.json"
DB = ROOT / "data" / "processed" / "structured" / "novatel_structured.db"
CHUNKS = ROOT / "data" / "processed" / "chunks"
WIP_QUERYSET = "wip/e15-partial-unvalidated:eval/e15/queryset.json"

HELD_OUT = ["S02", "S05", "S08", "S10", "S11", "S13", "S14"]
E14_CATEGORY = {"structured": "db", "unstructured_synthetic": "syn", "unstructured_public": "trai"}

CLAUDE = "written by Claude Code, UNREVIEWED"
PERSON_B = "Person B reference"

# Atomic gold facts for the document<->document questions (authored by Claude Code from the incident report and RCA text;
# each anchor was verified to occur in its document -- see verify_doc_anchor). Facts without anchors are judged per fact.
DOC_DOC_FACTS = {
    "MH01": [("The fault was detected at 06:12 IST", ["06:12"]),
             ("The primary fibre path was restored at 09:15", ["09:15"]),
             ("The RCA found no automatic failover to microwave backhaul was configured for the cluster", [])],
    "MH02": [("About 12,000 postpaid customers were billed twice", ["12,000"]),
             ("The duplicate charges were auto-reversed within 48 hours", ["48 hours"]),
             ("A scheduler configuration change left the previous month's billing job trigger active so the batch ran twice", [])],
    "MH03": [("Service was restored at 19:45 IST", ["19:45"]),
             ("The RCA prioritises route-diversity build-out for the Pune regional trunk", [])],
    "MH04": [("Logins were blocked for 55 minutes", ["55 minutes"]),
             ("A TLS certificate reference pointed to a staging certificate instead of production and the automated smoke tests did not "
              "check certificate validity or environment", [])],
    "MH05": [("The anti-fraud alert was broadcast within 4 hours", ["4 hours"]),
             ("There was no pre-existing rapid-takedown relationship with the hosting provider used for the phishing domain", [])],
}
ANCHOR_DOC = {"06:12": "INC_C08_INC_2026_0142", "09:15": "INC_C08_INC_2026_0142", "12,000": "INC_C04_INC_2026_0163",
              "48 hours": "INC_C04_INC_2026_0163", "19:45": "INC_C25_INC_2026_0179", "55 minutes": "INC_C13_INC_2026_0184",
              "4 hours": "INC_C18_INC_2026_0197"}


def _doc_text(doc_id: str) -> str:
    return " ".join(json.loads(f.read_text(encoding="utf-8")).get("text", "") for f in sorted(CHUNKS.glob(f"{doc_id}_chunk_*.json")))


def verify_doc_anchor(anchor: str) -> bool:
    return anchor.lower() in _doc_text(ANCHOR_DOC[anchor]).lower()


def _same(a, b) -> bool:
    try:
        return abs(float(a) - float(b)) < 1e-6
    except (TypeError, ValueError):
        return str(a) == str(b)


def verify_sql_fact(fact: dict) -> bool:
    """Re-query SQLite: the row (table, primary key) must exist and the field must hold the stated value."""
    from schema import get_schema
    pk = get_schema(fact["table"])["primary_key"]
    con = sqlite3.connect(f"file:{DB.as_posix()}?mode=ro", uri=True)
    try:
        row = con.execute(f"SELECT {fact['field']} FROM {fact['table']} WHERE {pk} = ?", (fact["record_id"],)).fetchone()
    finally:
        con.close()
    return row is not None and _same(row[0], fact["value"])


def build() -> dict:
    index_docs = {m["document_id"] for m in json.loads(INDEX_META.read_text(encoding="utf-8"))}
    questions, dropped = [], []

    def drop(qid, why):
        dropped.append({"id": qid, "reason": why})

    # ---- E14a (22) ---------------------------------------------------------------------------------------------
    for q in json.loads(E14A.read_text(encoding="utf-8"))["queries"]:
        ref, cat = q["reference_evidence"], E14_CATEGORY[q["intended_category"]]
        item = {"id": q["query_id"], "category": cat, "subtype": "e14a", "is_core": True, "query": q["question"],
                "gold_source": "E14a", "reference": ref, "gold_facts": [], "gold_ids": [], "notes": ""}
        if ref["kind"] == "sql_record":
            gt = e14._sql_ground_truth(ref)
            if ref.get("expected_table") and gt["kind"] in ("no_rows",) or (ref.get("expected_table") and not gt.get("anchors")):
                drop(q["query_id"], f"SQL ground truth not computable: {gt['kind']}")
                continue
            item["gold_sql"] = gt
            item["gold_ids"] = ([f"{ref['expected_table']}:{pk}" for pk in gt.get("anchors", [])] if gt["kind"] == "rows"
                                else [f"{ref['expected_table']}:aggregate"] if gt["kind"] == "aggregate_count" else [])
            item["gold_facts"] = ([{"text": f"count = {gt['count']}", "kind": "sql", "anchors": gt["anchors"]}] if gt["kind"] == "aggregate_count"
                                  else [{"text": f"{ref['expected_table']} row {pk}", "kind": "sql", "anchors": [pk]} for pk in gt.get("anchors", [])]
                                  if gt["kind"] == "rows" else [])
            if gt["kind"] == "abstention_expected":
                item["notes"] = "negative control: the correct behaviour is to abstain"
        else:
            missing = [d for d in ref["expected_document_ids"] if d not in index_docs]
            if missing:
                drop(q["query_id"], f"gold document id(s) not in the clean index: {missing}")
                continue
            item["gold_ids"] = list(ref["expected_document_ids"])
            item["notes"] = "judged against the text of the gold document(s) (E14a judge); no atomic facts defined by E14a"
        questions.append(item)

    # ---- held-out database (7) ---------------------------------------------------------------------------------------
    bench = {r["id"]: r for r in json.loads(STRUCT_BENCH.read_text(encoding="utf-8"))}
    for qid in HELD_OUT:
        row = bench[qid]
        ref = {"kind": "sql_record", "expected_table": row["expected_table"], "expected_method": row["expected_method"],
               "expected_filter_column": row.get("expected_filter_column"), "expected_filter_value": row.get("expected_filter_value"),
               "benchmark_query_type": row["query_type"]}
        gt = e14._sql_ground_truth(ref)
        if not gt.get("anchors"):
            drop(qid, f"SQL ground truth not computable: {gt['kind']}")
            continue
        questions.append({"id": qid, "category": "db", "subtype": "held_out", "is_core": False, "query": row["question"],
                          "gold_source": PERSON_B, "reference": ref, "gold_sql": gt,
                          "gold_ids": [f"{ref['expected_table']}:{pk}" for pk in gt["anchors"]] if gt["kind"] == "rows" else [f"{ref['expected_table']}:aggregate"],
                          "gold_facts": [{"text": f"{ref['expected_table']} row {pk}", "kind": "sql", "anchors": [pk]} for pk in gt["anchors"]]
                          if gt["kind"] == "rows" else [{"text": f"count = {gt['count']}", "kind": "sql", "anchors": gt["anchors"]}],
                          "notes": "ground truth computed from SQLite from Person B's structured benchmark item"})

    # ---- multi-hop (13), read from the wip branch without checking it out ---------------------------------------------------
    wip = json.loads(subprocess.run(["git", "show", WIP_QUERYSET], capture_output=True, text=True, encoding="utf-8", cwd=ROOT).stdout)
    for q in wip["queries"]:
        if q["category"] != "multihop":
            continue
        qid, sub, ref = q["query_id"], q["subtype"], q["reference_evidence"]
        cat = {"doc_doc": "multi", "sql_sql": "multi", "sql_doc": "cross"}[sub]
        facts, problems = [], []
        for f in ref.get("sql_facts", []):
            if f["field"] in ("count_for_customer",) or f["value"] is None:
                continue
            ok = verify_sql_fact(f)
            if not ok:
                problems.append(f"SQL fact not confirmed in SQLite: {f}")
            facts.append({"text": f"{f['table']} {f['record_id']}: {f['field']} = {f['value']}", "kind": "sql", "anchors": [str(f["value"])],
                          "sql": f, "verified": ok})
        if sub == "doc_doc":
            for text, anchors in DOC_DOC_FACTS[qid]:
                for a in anchors:
                    if not verify_doc_anchor(a):
                        problems.append(f"document anchor {a!r} not found in {ANCHOR_DOC[a]}")
                facts.append({"text": text, "kind": "doc", "anchors": anchors, "verified": True})
        if sub == "sql_doc":
            facts.append({"text": "the policy part of the answer matches the gold documents", "kind": "doc_policy", "anchors": [], "verified": True})
        missing = [d for d in ref.get("expected_document_ids", []) if d not in index_docs]
        if missing:
            problems.append(f"gold document id(s) not in the clean index: {missing}")
        if problems:
            drop(qid, "; ".join(problems))
            continue
        questions.append({
            "id": qid, "category": cat, "subtype": sub, "is_core": False, "query": q["question"],
            "gold_source": PERSON_B if sub == "sql_doc" else CLAUDE, "reference": ref, "gold_facts": facts,
            "gold_ids": list(ref.get("expected_document_ids", [])) + [f"{x['sql']['table']}:{x['sql']['record_id']}" for x in facts if x["kind"] == "sql"],
            "notes": ("Person B's expected_structured facts and expected_document_ids (route_benchmark.json item "
                      f"{ref.get('source_question_id')}); the 'For customer <id>:' prefix and the atomic fact split were added by Claude Code, UNREVIEWED"
                      if sub == "sql_doc" else "question, reference answer and fact split written by Claude Code from the cited documents / SQLite rows, UNREVIEWED")})

    # ---- review status + outputs --------------------------------------------------------------------------------------------
    approved = set()
    ap = OUT / "review_approved.json"
    if ap.exists():
        approved = set(json.loads(ap.read_text(encoding="utf-8")))
    for q in questions:
        q["reviewed"] = q["id"] in approved or q["gold_source"] == "E14a"

    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / "questions.jsonl", "w", encoding="utf-8") as f:
        for q in questions:
            f.write(json.dumps(q, ensure_ascii=False, default=str) + "\n")
    with open(OUT / "review_gold.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["id", "query", "gold_answer", "gold_ids", "gold_source", "approved", "notes"])
        for q in questions:
            if q["gold_source"] == "E14a":
                continue
            ref = q["reference"]
            gold_answer = ref.get("reference_answer") or "; ".join(x["text"] for x in q["gold_facts"]) or str(q.get("gold_sql", {}).get("anchors"))
            w.writerow([q["id"], q["query"], gold_answer, " | ".join(q["gold_ids"]), q["gold_source"], "", ""])
    (OUT / "questions_dropped.json").write_text(json.dumps(dropped, indent=2), encoding="utf-8")

    cats = {}
    for q in questions:
        cats[q["category"]] = cats.get(q["category"], 0) + 1
    n_docq = sum(1 for q in questions if q["category"] in ("syn", "trai") or q["reference"].get("expected_document_ids"))
    unreviewed = {}
    for q in questions:
        if not q["reviewed"]:
            unreviewed.setdefault(q["category"], []).append(q["id"])
    counts = {"n_total": len(questions), "n_db": cats.get("db", 0), "n_syn": cats.get("syn", 0), "n_trai": cats.get("trai", 0),
              "n_cross": cats.get("cross", 0), "n_multi": cats.get("multi", 0), "n_core": sum(q["is_core"] for q in questions),
              "n_new": sum(not q["is_core"] for q in questions), "n_docq": n_docq, "per_category": cats,
              "dropped": dropped, "unreviewed_by_category": unreviewed,
              "review_approved_file": "present" if ap.exists() else "absent (no id is marked reviewed beyond E14a's own gold)"}
    (OUT / "question_counts.json").write_text(json.dumps(counts, indent=2), encoding="utf-8")
    return counts


if __name__ == "__main__":
    c = build()
    print(json.dumps({k: v for k, v in c.items() if k != "dropped"}, indent=2))
    print("dropped:", c["dropped"] or "none")
